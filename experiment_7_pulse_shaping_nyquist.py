# ============================================================
# 12. TRANSMITTER + RECEIVER RRC CASCADE
# ============================================================

tx_rrc = root_raised_cosine(
    t,
    Ts,
    alpha_stream
)

rx_rrc = root_raised_cosine(
    t,
    Ts,
    alpha_stream
)

# Cascade
overall_rc = np.convolve(
    tx_rrc,
    rx_rrc,
    mode="full"
)

overall_rc = (
    overall_rc
    / np.max(np.abs(overall_rc))
)

cascade_time = (
    np.arange(len(overall_rc))
    - (len(overall_rc) - 1) / 2
) * Ts / sps

